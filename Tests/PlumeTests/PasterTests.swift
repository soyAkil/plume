import AppKit
import Carbon.HIToolbox
import Testing
@testable import Plume

/// What a dictation leaves on the pasteboard, without simulating anything on the keyboard.
/// Always a named pasteboard, never the general one: the user loses nothing during the tests.
@Suite("Pasteboard")
@MainActor
struct PasterTests {
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private func withPasteboard(_ body: (NSPasteboard) -> Void) {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("plume-tests-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        body(pasteboard)
    }

    @Test func aDictationThatWillBeReplacedCarriesTransientMarks() {
        withPasteboard { pasteboard in
            pasteboard.clearContents()
            pasteboard.setString("contenu d'avant", forType: .string)
            let saved = Paster.stage("la dictée", restoreClipboard: true, on: pasteboard)
            #expect(pasteboard.pasteboardItems?.count == 1)
            #expect(pasteboard.string(forType: .string) == "la dictée")
            #expect(pasteboard.types?.contains(Self.transient) == true)
            #expect(pasteboard.types?.contains(Self.autoGenerated) == true)
            #expect(saved?.count == 1)
            #expect(saved?.first?.string(forType: .string) == "contenu d'avant")
        }
    }

    @Test func aDictationThatStaysBelongsToClipboardManagers() {
        withPasteboard { pasteboard in
            pasteboard.clearContents()
            pasteboard.setString("contenu d'avant", forType: .string)
            let saved = Paster.stage("la dictée", restoreClipboard: false, on: pasteboard)
            #expect(saved == nil)
            #expect(pasteboard.string(forType: .string) == "la dictée")
            #expect(pasteboard.types?.contains(Self.transient) == false)
            #expect(pasteboard.types?.contains(Self.autoGenerated) == false)
        }
    }

    @Test func aPlainCopyCarriesNoMark() {
        withPasteboard { pasteboard in
            Paster.copy("texte", to: pasteboard)
            #expect(pasteboard.pasteboardItems?.count == 1)
            #expect(pasteboard.string(forType: .string) == "texte")
            #expect(pasteboard.types?.contains(Self.transient) == false)
        }
    }

    /// Everything comes back, not just the text: several items, several formats each. Rich
    /// text or an image must not turn back into plain text.
    @Test func previousContentComesBackAfterPasting() {
        withPasteboard { pasteboard in
            pasteboard.clearContents()
            let first = NSPasteboardItem()
            first.setString("contenu d'avant", forType: .string)
            first.setString("<b>contenu d'avant</b>", forType: .html)
            let second = NSPasteboardItem()
            second.setString("deuxième élément", forType: .string)
            pasteboard.writeObjects([first, second])
            let saved = Paster.stage("la dictée", restoreClipboard: true, on: pasteboard) ?? []
            Paster.restore(saved, to: pasteboard, ifUnchangedSince: pasteboard.changeCount)
            let items = pasteboard.pasteboardItems ?? []
            #expect(items.count == 2)
            #expect(items.first?.string(forType: .string) == "contenu d'avant")
            #expect(items.first?.string(forType: .html) == "<b>contenu d'avant</b>")
            #expect(items.last?.string(forType: .string) == "deuxième élément")
            #expect(pasteboard.types?.contains(Self.transient) == false)
        }
    }

    @Test func anEmptyPasteboardBecomesEmptyAgain() {
        withPasteboard { pasteboard in
            pasteboard.clearContents()
            let saved = Paster.stage("la dictée", restoreClipboard: true, on: pasteboard)
            #expect(saved?.isEmpty == true)
            #expect(pasteboard.types?.contains(Self.transient) == true)
            Paster.restore(saved ?? [], to: pasteboard, ifUnchangedSince: pasteboard.changeCount)
            #expect(pasteboard.string(forType: .string) == nil)
        }
    }

    /// Games (Minecraft, through GLFW) poll the modifier keys instead of reading the flags on
    /// the key event: ⌘ has to be pressed for real around the V, and released after.
    @Test func aShortcutPressesItsModifiersForReal() {
        let v = CGKeyCode(9)
        #expect(Paster.keystrokes(key: v, flags: .maskCommand) == [
            Paster.Keystroke(key: CGKeyCode(kVK_Command), down: true, flags: .maskCommand),
            Paster.Keystroke(key: v, down: true, flags: .maskCommand),
            Paster.Keystroke(key: v, down: false, flags: .maskCommand),
            Paster.Keystroke(key: CGKeyCode(kVK_Command), down: false, flags: []),
        ])
    }

    @Test func aPlainKeyIsJustPressedAndReleased() {
        let enter = CGKeyCode(kVK_Return)
        #expect(Paster.keystrokes(key: enter, flags: []) == [
            Paster.Keystroke(key: enter, down: true, flags: []),
            Paster.Keystroke(key: enter, down: false, flags: []),
        ])
    }

    @Test func severalModifiersAreReleasedInReverseOrder() {
        let enter = CGKeyCode(kVK_Return)
        #expect(Paster.keystrokes(key: enter, flags: [.maskShift, .maskCommand]) == [
            Paster.Keystroke(key: CGKeyCode(kVK_Shift), down: true, flags: .maskShift),
            Paster.Keystroke(key: CGKeyCode(kVK_Command), down: true, flags: [.maskShift, .maskCommand]),
            Paster.Keystroke(key: enter, down: true, flags: [.maskShift, .maskCommand]),
            Paster.Keystroke(key: enter, down: false, flags: [.maskShift, .maskCommand]),
            Paster.Keystroke(key: CGKeyCode(kVK_Command), down: false, flags: .maskShift),
            Paster.Keystroke(key: CGKeyCode(kVK_Shift), down: false, flags: []),
        ])
    }

    /// A slow transcription (model loading) only leaves the text on the clipboard if the user
    /// has left the app in the meantime; a game with no bundle identifier counts as the same app.
    @Test func aLongWaitOnlyCopiesIfTheAppChanged() {
        #expect(!SessionController.cursorProbablyMoved(waited: 3, startedIn: "a", nowIn: "b"))
        #expect(!SessionController.cursorProbablyMoved(waited: 20, startedIn: "a", nowIn: "a"))
        #expect(!SessionController.cursorProbablyMoved(waited: 20, startedIn: nil, nowIn: nil))
        #expect(SessionController.cursorProbablyMoved(waited: 20, startedIn: "a", nowIn: "b"))
        #expect(SessionController.cursorProbablyMoved(waited: 20, startedIn: nil, nowIn: "b"))
    }

    @Test func aCopyMadeInTheMeantimeStays() {
        withPasteboard { pasteboard in
            pasteboard.clearContents()
            pasteboard.setString("contenu d'avant", forType: .string)
            let saved = Paster.stage("la dictée", restoreClipboard: true, on: pasteboard) ?? []
            let marker = pasteboard.changeCount
            pasteboard.clearContents()
            pasteboard.setString("copié entre-temps", forType: .string)
            Paster.restore(saved, to: pasteboard, ifUnchangedSince: marker)
            #expect(pasteboard.string(forType: .string) == "copié entre-temps")
        }
    }
}
